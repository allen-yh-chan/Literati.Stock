/**
 * Forbidden attribution patterns.
 *
 * Per ai-autonomy.md §行為邊界 (Always), gh body AND git commit message MUST reject all
 * forbidden attribution variants. Both hooks import from here to guarantee
 * symmetry. Adding a pattern here automatically enforces it on both surfaces
 * without further code changes.
 *
 * Sanitization notes (per rule-design-principles.md §Example Sanitization):
 *   - Claude-specific patterns (F1–F2): match the exact tool link strings
 *     emitted by Claude tooling; no false-positive risk on natural prose.
 *   - F3 AI-host Co-Authored-By brands: match trailers whose author token is a
 *     known AI host brand (Claude / Cursor / Copilot / Codex / Gemini /
 *     ChatGPT / Windsurf). MUST NOT include name-collision tokens such as
 *     Devin or Cody (common human given names). MUST NOT be implemented as a
 *     blanket `/Co-Authored-By:/i` ban — legitimate human co-author trailers
 *     (e.g. Jane Doe) MUST pass.
 *   - Generic tool-brand sentence patterns (F4–F5): anchored with ^…$ + m flag
 *     so only a WHOLE LINE that is exactly a brand-marker sentence matches.
 *     This prevents false positives on natural commit prose such as
 *     "fix: handle files generated by the build script" (the match would
 *     require the entire line to be "Generated by <BrandWord>", not a phrase
 *     embedded in a longer sentence). [A-Z][\w.\s-]* requires the brand word to
 *     be capitalized, excluding lowercase natural-language fragments like
 *     "made with care for edge cases" or "Generated by" alone (no brand word).
 *     The hyphen in the char class covers hyphenated and versioned brand names
 *     of the form `<Tool>-<version>` (e.g. a tool name with a version suffix).
 */
export const FORBIDDEN_ATTRIBUTION_PATTERNS = [
  /🤖\s*Generated with\s*\[?Claude/i,        // F1: 🤖 Generated with [Claude Code] / 🤖 Generated with Claude
  /Generated with\s*\[Claude Code\]/i,        // F2: markdown link variant without emoji
  /Co-Authored-By:\s*(?:Claude|Cursor|Copilot|Codex|Gemini|ChatGPT|Windsurf)\b/i, // F3: AI-host Co-Authored-By brands (excludes Devin/Cody name collisions; MUST NOT ban-all Co-Authored-By)
  /^(?:🤖\s*)?Made with [A-Z][\w.\s-]*$/m,  // F4: whole-line brand sentence "Made with <Tool>" (e.g. "Made with Claude", "Made with Cursor"); ^/$ with m-flag anchors to a single line; [A-Z] requires capitalized brand name (excludes lowercase natural prose like "made with care"); hyphen in char class covers versioned/hyphenated brand names
  /^(?:🤖\s*)?Generated by [A-Z][\w.\s-]*$/m, // F5: whole-line brand sentence "Generated by <Tool>" (e.g. "Generated by Copilot", "🤖 Generated by Cursor"); [A-Z] excludes "generated by the build" (lowercase g + not a whole line); hyphen in char class covers versioned/hyphenated brand names
];

export function hasForbiddenAttribution(text) {
  return FORBIDDEN_ATTRIBUTION_PATTERNS.some((re) => re.test(text));
}
