/**
 * @param {string} filename suite-relative path
 * @returns {"unit" | "integration"}
 */
export function resolveTier(filename) {
  const tier = MANIFEST[filename];
  if (!tier) {
    throw new Error(`test-suite-manifest: unknown file "${filename}"`);
  }
  return tier;
}

/** @returns {string[]} sorted relative paths like .devpro/scripts/tests/foo.test.mjs */
export function getAllManifestFiles() {
  return Object.keys(MANIFEST)
    .sort()
    .map((f) => `${SUITE_DIR}${f}`);
}

/**
 * @param {"unit" | "integration" | "all"} tier
 * @returns {string[]} sorted relative paths
 */
export function listFiles(tier) {
  if (tier === "all") return getAllManifestFiles();
  return Object.entries(MANIFEST)
    .filter(([, t]) => t === tier)
    .map(([f]) => f)
    .sort()
    .map((f) => `${SUITE_DIR}${f}`);
}
